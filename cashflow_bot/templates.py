from datetime import datetime
from zoneinfo import ZoneInfo

from .config import settings

TZ = ZoneInfo(settings.timezone)

WEEKDAYS = (
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье",
)
MONTHS = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)


def format_when(iso: str) -> str:
    """«13 августа, четверг · 18:00» — так же, как игра подписана в CRM."""
    moment = datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone(TZ)
    return (
        f"{moment.day} {MONTHS[moment.month - 1]}, "
        f"{WEEKDAYS[moment.weekday()]} · {moment:%H:%M}"
    )


def format_price(price: float, currency: str) -> str:
    units = {"KGS": "сом", "USD": "$", "RUB": "₽"}.get(currency, currency)
    amount = f"{price:,.0f}".replace(",", " ")
    return f"{amount} {units}" if currency == "KGS" else f"{amount}{units}"


def seats_line(free: int) -> str:
    if free <= 0:
        return "мест нет"
    if free == 1:
        return "осталось 1 место"
    if free <= 3:
        return f"осталось {free} места"
    return f"свободно {free}"


